from __future__ import annotations

from pathlib import Path

from artisan_maker_models import ArtisanMakerResult
from artisan_maker_quality import (
    _append_readme_qa,
    _best_output_folder,
    _blender_binary,
    _candidate_blender_scripts,
    _files,
    _has_outputs,
    _mesh_dimensions,
    _read,
    _render_preview,
    _run_blender_script,
    _script_safety_issue,
    _title_from_request,
    _write_fallback_source,
    _write_readme,
)


def complete_blender_maker_output(
    cwd: str | Path,
    *,
    request: str = "",
    brief: str = "",
    allow_fallback: bool = True,
) -> ArtisanMakerResult:
    root = Path(cwd).expanduser()
    issues: list[str] = []
    warnings: list[str] = []
    checks: list[str] = []
    scripts = _candidate_blender_scripts(root)
    if not scripts and allow_fallback:
        fallback = _write_fallback_source(root, request)
        if fallback:
            warnings.append("Artisan did not produce Blender source before timeout; Maya wrote a constrained local fallback generator.")
            scripts = [fallback]
    if not scripts:
        return ArtisanMakerResult(
            False,
            "No Blender Python source was produced.",
            ["missing Blender Python source script"],
            warnings,
            checks,
            [],
            [],
            [],
            [],
            [],
            {},
        )
    checks.append(f"Blender source scripts found: {len(scripts)}")

    blender = _blender_binary()
    if not blender:
        issues.append("Blender binary not found; cannot export maker artifact")
    elif not _has_outputs(root):
        for script in scripts[:3]:
            safety_issue = _script_safety_issue(script)
            if safety_issue:
                issues.append(f"{script.name}: {safety_issue}")
                continue
            ok, detail = _run_blender_script(blender, script)
            if ok:
                checks.append(f"Blender export script ran: {script.relative_to(root)}")
            else:
                issues.append(detail)
            if _has_outputs(root):
                break

    blend_files = _files(root, ("*.blend",))
    mesh_files = _files(root, ("*.stl", "*.3mf", "*.obj"))
    preview_files = _files(root, ("*preview*.png", "*preview*.jpg", "*preview*.jpeg"))
    readme_files = _files(root, ("README.md", "readme.md"))
    if not readme_files:
        readme = _write_readme(root, request=request, brief=brief, scripts=scripts, blend_files=blend_files, mesh_files=mesh_files)
        readme_files = [readme]
        checks.append("README generated by Maya maker completion")

    if not blend_files:
        issues.append("missing editable .blend output")
    if not mesh_files:
        issues.append("missing exported mesh output (.stl/.3mf/.obj)")
    for path in blend_files + mesh_files:
        if path.stat().st_size < 256:
            issues.append(f"output file too small: {path.name}")

    dimensions = _mesh_dimensions(mesh_files)
    for name, dims in dimensions.items():
        if any(value <= 0.1 for value in dims):
            issues.append(f"mesh dimension too small for {name}: {dims}")
        if any(value > 1000 for value in dims):
            issues.append(f"mesh dimension too large for {name}: {dims}")
    if dimensions:
        checks.append("mesh dimensions extracted in millimeters")
    elif mesh_files:
        warnings.append("mesh dimensions could not be extracted")

    if blend_files and not preview_files:
        preview = _render_preview(blend_files[0])
        if preview:
            preview_files = [preview]
            checks.append("preview render generated")
    if not preview_files:
        warnings.append("preview render unavailable")

    _append_readme_qa(readme_files, dimensions, preview_files)

    if blend_files:
        checks.append(f"editable Blender files: {len(blend_files)}")
    if mesh_files:
        checks.append(f"print/export mesh files: {len(mesh_files)}")
    if readme_files:
        checks.append(f"README files: {len(readme_files)}")
    if preview_files:
        checks.append(f"preview files: {len(preview_files)}")

    summary = "Blender maker QA passed." if not issues else "Blender maker QA failed."
    return ArtisanMakerResult(
        not issues,
        summary,
        issues,
        warnings,
        checks,
        [str(path) for path in scripts],
        [str(path) for path in blend_files],
        [str(path) for path in mesh_files],
        [str(path) for path in readme_files],
        [str(path) for path in preview_files],
        dimensions,
    )
