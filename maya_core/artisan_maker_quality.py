def _candidate_blender_scripts(root: Path) -> list[Path]:
    scripts: list[Path] = []
    for path in root.rglob("*.py"):
        if "__pycache__" in path.parts:
            continue
        text = _read(path)
        if "import bpy" in text or "from bpy" in text:
            scripts.append(path)
    return sorted(scripts, key=lambda path: (len(path.parts), str(path)))

def _has_outputs(root: Path) -> bool:
    return bool(_files(root, ("*.blend",)) and _files(root, ("*.stl", "*.3mf", "*.obj")))


def _files(root: Path, patterns: tuple[str, ...]) -> list[Path]:
    found: list[Path] = []
    for pattern in patterns:
        found.extend(path for path in root.rglob(pattern) if path.is_file() and "__pycache__" not in path.parts)
    return sorted(set(found), key=str)


def _blender_binary() -> str:
    path = shutil.which("blender")
    if path:
        return path
    app_binary = Path("/Applications/Blender.app/Contents/MacOS/Blender")
    return str(app_binary) if app_binary.exists() else ""


def _script_safety_issue(script: Path) -> str:
    text = _read(script).lower()
    blocked = (
        "subprocess", "os.system", "popen(", "socket.", "requests.", "urllib.request",
        "shutil.rmtree", "rm -rf", "eval(", "exec(",
    )
    for marker in blocked:
        if marker in text:
            return f"blocked unsafe marker `{marker}`"
    return ""


def _run_blender_script(blender: str, script: Path) -> tuple[bool, str]:
    with tempfile.TemporaryDirectory(prefix="maya-blender-maker-runtime-") as tmp:
        env = os.environ.copy()
        root = Path(tmp)
        env.update(
            {
                "BLENDER_USER_CONFIG": str(root / "config"),
                "BLENDER_USER_SCRIPTS": str(root / "scripts"),
                "BLENDER_USER_EXTENSIONS": str(root / "extensions"),
            }
        )
        proc = subprocess.run(
            [
                blender,
                "--background",
                "--factory-startup",
                "--python-exit-code",
                "11",
                "--python",
                str(script),
            ],
            cwd=str(script.parent),
            capture_output=True,
            text=True,
            timeout=90,
            env=env,
        )
    if proc.returncode == 0:
        return True, ""
    output = "\n".join(part for part in (proc.stdout, proc.stderr) if part).strip()
    return False, f"Blender script failed for {script.name}: {output[:500]}"


def _write_readme(
    root: Path,
    *,
    request: str,
    brief: str,
    scripts: list[Path],
    blend_files: list[Path],
    mesh_files: list[Path],
) -> Path:
    folder = _best_output_folder(root, scripts, blend_files, mesh_files)
    readme = folder / "README.md"
    title = _title_from_request(request) or "Artisan Blender Maker Output"
    lines = [
        f"# {title}",
        "",
        "Generated by Maya's Artisan maker workflow.",
        "",
        "## Files",
    ]
    for label, paths in (("Source", scripts), ("Editable Blender", blend_files), ("Mesh export", mesh_files)):
        if paths:
            for path in paths:
                try:
                    rel = path.relative_to(folder)
                except ValueError:
                    rel = path
                lines.append(f"- {label}: `{rel}`")
    lines.extend(
        [
            "",
            "## Safety",
            "- This workflow stops at local source/export files.",
            "- Maya does not slice, upload, or start a physical print automatically.",
            "- Inspect scale, tolerances, and material settings before printing.",
        ]
    )
    if brief.strip():
        lines.extend(["", "## Build Brief", brief.strip()[:1200]])
    readme.write_text("\n".join(lines).strip() + "\n", encoding="utf-8")
    return readme


def _best_output_folder(root: Path, *groups: list[Path]) -> Path:
    paths = [path for group in groups for path in group]
    if paths:
        return paths[0].parent
    return root


def _title_from_request(request: str) -> str:
    text = re.sub(r"\b(make|create|build|generate|save|editable|blender|source|stl|readme|real|project|folder)\b", " ", request, flags=re.I)
    text = re.sub(r"\s+", " ", text).strip(" .")
    return text[:80].title()


def _read(path: Path) -> str:
    try:
        return path.read_text("utf-8")
    except UnicodeDecodeError:
        return path.read_text("utf-8", errors="replace")
    except OSError:
        return ""


