def _mesh_dimensions(mesh_files: list[Path]) -> dict[str, list[float]]:
    dimensions: dict[str, list[float]] = {}
    for path in mesh_files:
        bounds = _stl_bounds(path) if path.suffix.lower() == ".stl" else _obj_bounds(path)
        if not bounds:
            continue
        mins, maxs = bounds
        dimensions[path.name] = [round(maxs[i] - mins[i], 2) for i in range(3)]
    return dimensions


def _stl_bounds(path: Path) -> tuple[list[float], list[float]] | None:
    data = path.read_bytes()
    vertices: list[tuple[float, float, float]] = []
    if len(data) >= 84:
        triangles = struct.unpack("<I", data[80:84])[0]
        expected = 84 + triangles * 50
        if expected == len(data):
            for offset in range(84, expected, 50):
                for idx in range(3):
                    start = offset + 12 + idx * 12
                    vertices.append(struct.unpack("<fff", data[start:start + 12]))
            return _bounds(vertices)
    text = data.decode("utf-8", errors="ignore")
    for match in re.finditer(r"\bvertex\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)", text, re.I):
        vertices.append(tuple(float(part) for part in match.groups()))
    return _bounds(vertices)


def _obj_bounds(path: Path) -> tuple[list[float], list[float]] | None:
    vertices: list[tuple[float, float, float]] = []
    for line in _read(path).splitlines():
        if not line.startswith("v "):
            continue
        parts = line.split()
        if len(parts) >= 4:
            vertices.append((float(parts[1]), float(parts[2]), float(parts[3])))
    return _bounds(vertices)


def _bounds(vertices: list[tuple[float, float, float]]) -> tuple[list[float], list[float]] | None:
    if not vertices:
        return None
    mins = [min(vertex[i] for vertex in vertices) for i in range(3)]
    maxs = [max(vertex[i] for vertex in vertices) for i in range(3)]
    return mins, maxs


def _render_preview(blend_file: Path) -> Path | None:
    blender = _blender_binary()
    if not blender:
        return None
    preview = blend_file.with_name(f"{blend_file.stem}-preview.png")
    script = f"""
import math
from pathlib import Path

import bpy
from mathutils import Vector

preview = Path({str(preview)!r})
for obj in bpy.context.scene.objects:
    obj.select_set(obj.type == 'MESH')
meshes = [obj for obj in bpy.context.scene.objects if obj.type == 'MESH']
if meshes:
    center = sum((obj.location for obj in meshes), Vector()) / len(meshes)
else:
    center = Vector((0, 0, 0))
light_data = bpy.data.lights.new('maya_preview_light', type='AREA')
light = bpy.data.objects.new('maya_preview_light', light_data)
bpy.context.collection.objects.link(light)
light.location = (120, -160, 180)
light.data.energy = 450
light.data.size = 5
cam_data = bpy.data.cameras.new('maya_preview_camera')
cam = bpy.data.objects.new('maya_preview_camera', cam_data)
bpy.context.collection.objects.link(cam)
cam.location = (140, -170, 110)
direction = center - cam.location
cam.rotation_euler = direction.to_track_quat('-Z', 'Y').to_euler()
cam.data.lens = 45
bpy.context.scene.camera = cam
bpy.context.scene.render.resolution_x = 1200
bpy.context.scene.render.resolution_y = 900
bpy.context.scene.render.filepath = str(preview)
bpy.context.scene.eevee.taa_render_samples = 32 if hasattr(bpy.context.scene, 'eevee') else 16
bpy.ops.render.render(write_still=True)
"""
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as handle:
        handle.write(script)
        script_path = Path(handle.name)
    try:
        proc = subprocess.run(
            [blender, "--background", str(blend_file), "--python-exit-code", "11", "--python", str(script_path)],
            capture_output=True,
            text=True,
            timeout=90,
        )
    finally:
        script_path.unlink(missing_ok=True)
    if proc.returncode == 0 and preview.exists() and preview.stat().st_size > 1024:
        return preview
    return None


def _append_readme_qa(readme_files: list[Path], dimensions: dict[str, list[float]], preview_files: list[Path]) -> None:
    if not readme_files:
        return
    readme = readme_files[0]
    text = _read(readme)
    if "## Maya QA" in text:
        return
    lines = ["", "## Maya QA"]
    if dimensions:
        for name, dims in dimensions.items():
            lines.append(f"- Mesh dimensions for `{name}`: {dims[0]} x {dims[1]} x {dims[2]} mm.")
    if preview_files:
        for preview in preview_files:
            lines.append(f"- Preview render: `{preview.name}`.")
    lines.append("- Physical printing, slicing, and printer upload require explicit confirmation.")
    readme.write_text(text.rstrip() + "\n" + "\n".join(lines) + "\n", encoding="utf-8")
